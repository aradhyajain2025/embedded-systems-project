"""Write fake_sensors_generated.c: a long scripted sensor table for the PIC firmware.

Readings come from generator.py and go through parse_frame, so the table holds exactly
what the PC parser accepts. Layout: normal, then intruder, then normal again.
Usage: python export_c_array.py [seed]
"""
import random
import sys
from frames import parse_frame
from generator import generate_frames, NORMAL, INTRUDER
from ids_pipeline import WINDOW

SCENARIO = [("normal", NORMAL, 200), ("intruder", INTRUDER, 100), ("normal", NORMAL, 100)]
OUT = "fake_sensors_generated.c"


def rows(values, per_line=20):
    return ",\n".join("    " + ", ".join(str(v) for v in values[i:i + per_line])
                      for i in range(0, len(values), per_line))


def main():
    random.seed(int(sys.argv[1]) if len(sys.argv) > 1 else 1)
    recs = []
    for _, mode, n in SCENARIO:
        recs += [parse_frame(f) for f in generate_frames(n, mode)]
    p, d, s = zip(*recs)
    n = len(recs)

    with open(OUT, "w") as f:
        f.write(f"""#include "fake_sensors.h"

/* Generated by export_c_array.py. Do not edit by hand.
   {n} frames: """ + ", ".join(f"{k} {c}" for k, _, c in SCENARIO) + f""".
   Table is in flash (about {n * 4} bytes). idx must be uint16_t because N > 255. */
#define N {n}

static const uint8_t P_T[N] = {{
{rows(p)}
}};
static const uint16_t D_T[N] = {{
{rows(d)}
}};
static const uint8_t S_T[N] = {{
{rows(s)}
}};

static uint16_t idx = 0;

void fake_sensors_next(uint8_t *p, uint16_t *d, uint8_t *s)
{{
    *p = P_T[idx];
    *d = D_T[idx];
    *s = S_T[idx];
    if (++idx >= N) idx = 0;
}}
""")

    print(f"Wrote {OUT}: {n} frames = {n // WINDOW} windows of {WINDOW}")
    start = 0
    for name, _, count in SCENARIO:
        print(f"  windows {start // WINDOW:2d} to {(start + count) // WINDOW - 1:2d}: {name}")
        start += count


main()
